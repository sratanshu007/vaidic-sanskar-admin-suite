const mongoose = require('mongoose');

const bookingSchema = new mongoose.Schema(
  {
    id: { type: String, required: true, unique: true, index: true },
    userId: { type: String, required: true, index: true },
    ritualId: { type: String, required: true },
    ritualName: { type: String, required: true },
    status: {
      type: String,
      required: true,
      enum: [
        'DRAFT',
        'PENDING_ACCEPTANCE',
        'ACCEPTED',
        'EN_ROUTE',
        'ARRIVED',
        'POOJA_STARTED',
        'COMPLETED',
        'REJECTED',
        'EXPIRED',
        'CANCELLED',
        'NO_SHOW',
        'UNABLE_TO_COMPLETE',
        'DISPUTED',
      ],
      default: 'PENDING_ACCEPTANCE',
      index: true,
    },
    scheduledDate: { type: String },
    scheduledTime: { type: String },
    serviceAddress: { type: String, required: true },
    serviceArea: { type: String },
    landmark: { type: String },
    destinationLatitude: { type: Number },
    destinationLongitude: { type: Number },
    samagriPreference: {
      type: String,
      enum: ['PANDIT_BRINGS', 'USER_ARRANGES'],
      default: 'PANDIT_BRINGS',
    },
    samagriFee: { type: Number, default: 0 },
    participantsCount: { type: Number, default: 1 },
    specialInstructions: { type: String },
    preferredLanguage: { type: String, default: 'Hindi & Sanskrit' },
    yajmanName: { type: String },
    gotra: { type: String },
    serviceCharge: { type: Number, required: true },
    travelFee: { type: Number, default: 0 },
    platformFee: { type: Number, default: 50 },
    taxes: { type: Number, default: 0 },
    totalAmount: { type: Number, required: true },
    advancePaid: { type: Number, default: 0 },
    assignedVendorId: { type: String, index: true },
    assignedVendor: {
      id: String,
      name: String,
      rating: Number,
      reviewsCount: Number,
      photo: String,
      experienceYears: Number,
      gurukul: String,
    },
    otps: {
      startOtp: {
        hash: String,
        expiresAt: Number,
        attempts: { type: Number, default: 0 },
        consumed: { type: Boolean, default: false },
        consumedAt: Date,
      },
      completeOtp: {
        hash: String,
        expiresAt: Number,
        attempts: { type: Number, default: 0 },
        consumed: { type: Boolean, default: false },
        consumedAt: Date,
      },
    },
    tracking: {
      vendorLatitude: Number,
      vendorLongitude: Number,
      distanceKm: Number,
      etaMinutes: Number,
      lastUpdated: Date,
      isSharingStopped: { type: Boolean, default: false },
    },
    cancellation: {
      cancelledBy: String,
      reason: String,
      refundPercent: Number,
      penaltyFee: Number,
      previousStatus: String,
      cancelledAt: Date,
    },
    dispute: {
      reason: String,
      details: String,
      ticketId: String,
      createdAt: Date,
    },
    acceptedAt: Date,
    enRouteAt: Date,
    arrivedAt: Date,
    startedAt: Date,
    completedAt: Date,
  },
  { timestamps: true }
);

module.exports = mongoose.models.Booking || mongoose.model('Booking', bookingSchema);
